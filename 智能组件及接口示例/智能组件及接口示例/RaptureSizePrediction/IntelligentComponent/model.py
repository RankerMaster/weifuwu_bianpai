import os
import numpy as np
from sklearn import preprocessing

import joblib

def rapturSizePrediction(X_timeserise):
    model_path = os.path.dirname(__file__)
    model_test = joblib.load(os.path.join(model_path, 'dependencies/RapturSizePrediction.model'))
    X_timeserise = np.array(X_timeserise)

    # testing a new prediction
    scaler = preprocessing.StandardScaler()
    x_new = scaler.fit_transform(X_timeserise.reshape(1, -1))
    y_new = model_test.predict(x_new)

    return y_new[0] / 10

def infer(req_data):
    output = rapturSizePrediction(req_data["input_series"])
    return output

